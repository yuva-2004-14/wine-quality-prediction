import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score
wine = pd.read_csv('/content/winequality-red.csv')
wine

wine.head()

wine.tail()

wine.shape # Total no of rows and columns

wine.isnull().sum() # no of null values

### Data Analysis and Visualization

# statistical measure of the dataset
wine.describe()

#number of values for each quality
sns.catplot(x='quality', data= wine,kind ='count') # catplot()--> It is a versatile tool for creating various types of categorical plots. It allows to visualize the relationship between a numerical and one or more categorical variables using different visual representation.
# It creates multiple subplots based on the categorical specify you specify.

#volatile acidity vs quality ---> volatile acidity is indirectly propostional to quality
plot=plt.figure(figsize=(5,5))
sns.barplot(x='quality',y='volatile acidity',data=wine)

# citric acid vs quality  ---> citric acid is directly propotional to quality
plot=plt.figure(figsize=(5,5))
sns.barplot(x='quality',y='citric acid',data=wine)

# residual sugar vs quality
plot = plt.figure(figsize=(5,5))
sns.barplot(x='quality',y='residual sugar',data=wine)

correlation = wine.corr()

# construct a heatmap to find the correlation between columns
plt.figure(figsize=(10,10))
sns.heatmap(correlation,cbar=True, square=True, fmt='.1f',annot=True,annot_kws={'size':8},cmap='Blues')

#Data Preprocessing

# seperate the data and class label
X = wine.drop('quality',axis=1)
print(X)

#Label Binarization
y= wine['quality'].apply(lambda y_value:1 if y_value>=7 else 0)
print(y)

## Train & Test split
X_train,X_test,y_train,y_test = train_test_split(X,y,test_size=0.2,random_state=3)

#Model Training: Random Forest Classifier ( It is an ensemble of decision tree)

model = RandomForestClassifier()
model.fit(X_train,y_train)

#Model Evualtion

# accuracy on test data
X_test_prediction = model.predict(X_test)
test_data_accuracy = accuracy_score(X_test_prediction,y_test)

print('Accuracy:',test_data_accuracy)

#Building a Predictive system
input_data = (7.4,0.700,0.00,1.9,0.076,11.0,34.0,0.99780,3.51,0.56,9.4) #tuple data
np_array=np.asarray(input_data)

#reshape the data as we are predicting the label only for one columns(instance)
input_data_reshaped = np_array.reshape(1,-1)
prediction = model.predict(input_data_reshaped)
print(prediction)

if (prediction[0]==1):
  print('It is a good quality wine')
else:
  print('It is a bad quality wine')